#!/usr/bin/env bun
/**
 * Regenerate src/vendor/bzip2-wasm/bzip2-wasm-data.ts from the vendored .wasm.
 *
 *   bun run tools/gen-bzip2-wasm.ts
 *
 * The single-file HTML cannot fetch a sibling .wasm, so the bytes are embedded
 * as base64 and passed to the Emscripten module through Module.wasmBinary.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const here = import.meta.dir;
const wasm = resolve(here, '../src/vendor/bzip2-wasm/bzip2.wasm');
const out = resolve(here, '../src/vendor/bzip2-wasm/bzip2-wasm-data.ts');
const b64 = readFileSync(wasm).toString('base64');
writeFileSync(out, '// generated by tools/gen-bzip2-wasm.ts — do not edit by hand\n' + 'export const bzip2WasmBase64 = ' + JSON.stringify(b64) + ';\n');
console.log('wrote ' + out + ' (' + b64.length + ' base64 bytes)');
