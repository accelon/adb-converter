#!/usr/bin/env python3
"""Build `accelon-box.woff2` — 製表符（box drawing）專用字型。

## 為什麼要自己做

厚觀法師 2026-11-14 20:14 回報《空之探究講義》2p41 的圖表，20:07 回報
《中觀論頌講記》5p34 的科判圖「不合」。兩者都是**用製表符排的文字圖**
（`┌─┬┐│└┴┘` ＋ 全形空格）。查下來是字寬問題：

    Microsoft JhengHei 的 U+2500–257F 是 **0.709em**（11.34px @16px）
    漢字與全形空格是 1em（16px）

於是每往右一個框線字元就少 4.66px，一行 40 格之後整張圖就散了。
紙本是用細明體排的（1em），我們用 JhengHei／TNR 排，寬度不同 → 走位。

`font-family` 只能整段指定，沒辦法「框線字元用 A、漢字用 B」；能做的只有
`@font-face` ＋ `unicode-range`，把 U+2500–257F 指到一個**每字 1em** 的字型。
系統裡有 1em 製表符的字型（細明體、宋體）都是專有授權、不能內嵌；Noto／
思源等 OFL 字型又不一定有製表符。所以這裡**自己畫**——這些字本來就是直線。

## 幾何

em = 1000，advance = 1000（＝一個漢字寬），線寬 70（粗線 130）。

- 橫線 y 中心 500，豎線 x 中心 500；`┌┐└┘├┤┬┴┼` 都在中心交會。
- 豎線 y 由 **-350 到 1350**（超出 em 方塊）：閱讀器的 line-height 約 1.5，
  若只在 em 內畫，上下行之間會斷線；紙本的 `│` 是連貫的。
- 橫線 x 由 0 到 1000（滿寬），相鄰兩字才接得起來。

## 用法

    python ts/tools/build-box-font.py            # 寫入 src/accelon26/fonts/
    python ts/tools/build-box-font.py --out DIR

需要 `pip install fonttools brotli`。
"""
import argparse
import os

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

EM = 1000
ADV = 1000
MID = 500
THIN = 70
THICK = 130
YTOP = 1350
YBOT = -350

# (code point, 名稱, 幾何) 幾何＝要填滿的矩形清單 (x0, y0, x1, y1)
LIGHT = {
    0x2500: [("h", 0, MID, 1000, MID)],                       # ─
    0x2502: [("v", MID, YBOT, MID, YTOP)],                    # │
    0x250C: [("v", MID, YBOT, MID, MID), ("h", MID, MID, 1000, MID)],   # ┌
    0x2510: [("v", MID, YBOT, MID, MID), ("h", 0, MID, MID, MID)],      # ┐
    0x2514: [("v", MID, MID, MID, YTOP), ("h", MID, MID, 1000, MID)],   # └
    0x2518: [("v", MID, MID, MID, YTOP), ("h", 0, MID, MID, MID)],      # ┘
    0x251C: [("v", MID, YBOT, MID, YTOP), ("h", MID, MID, 1000, MID)],  # ├
    0x2524: [("v", MID, YBOT, MID, YTOP), ("h", 0, MID, MID, MID)],     # ┤
    0x252C: [("h", 0, MID, 1000, MID), ("v", MID, YBOT, MID, MID)],     # ┬
    0x2534: [("h", 0, MID, 1000, MID), ("v", MID, MID, MID, YTOP)],     # ┴
    0x253C: [("h", 0, MID, 1000, MID), ("v", MID, YBOT, MID, YTOP)],    # ┼
}
HEAVY = {
    0x2501: "─", 0x2503: "│", 0x250F: "┌", 0x2513: "┐",
    0x2517: "└", 0x251B: "┘", 0x2523: "├", 0x252B: "┤",
    0x2533: "┬", 0x253B: "┴", 0x254B: "┼",
}
NAMES = {
    0x2500: "boxdraw_light_h", 0x2502: "boxdraw_light_v",
    0x250C: "boxdraw_light_dr", 0x2510: "boxdraw_light_dl",
    0x2514: "boxdraw_light_ur", 0x2518: "boxdraw_light_ul",
    0x251C: "boxdraw_light_vr", 0x2524: "boxdraw_light_vl",
    0x252C: "boxdraw_light_dh", 0x2534: "boxdraw_light_uh",
    0x253C: "boxdraw_light_vh",
    0x2501: "boxdraw_heavy_h", 0x2503: "boxdraw_heavy_v",
    0x250F: "boxdraw_heavy_dr", 0x2513: "boxdraw_heavy_dl",
    0x2517: "boxdraw_heavy_ur", 0x251B: "boxdraw_heavy_ul",
    0x2523: "boxdraw_heavy_vr", 0x252B: "boxdraw_heavy_vl",
    0x2533: "boxdraw_heavy_dh", 0x253B: "boxdraw_heavy_uh",
    0x254B: "boxdraw_heavy_vh",
}


def rect(pen, x0, y0, x1, y1):
    """一條水平或垂直的線，給的是中心線與方向；實際填成有寬度的矩形。"""
    if y0 == y1:  # 橫線
        half = _w / 2
        y0, y1 = y0 - half, y0 + half
    if x0 == x1:  # 豎線
        half = _w / 2
        x0, x1 = x0 - half, x0 + half
    pen.moveTo((x0, y0))
    pen.lineTo((x1, y0))
    pen.lineTo((x1, y1))
    pen.lineTo((x0, y1))
    pen.closePath()


_w = THIN


def build(weight):
    """weight: THIN / THICK"""
    global _w
    _w = weight
    glyphs = {}
    cmap = {}
    order = [".notdef"]

    # .notdef：空白（不留豆腐）
    pen = TTGlyphPen(None)
    glyphs[".notdef"] = pen.glyph()

    for cp, segs in LIGHT.items():
        pen = TTGlyphPen(None)
        for _, x0, y0, x1, y1 in segs:
            rect(pen, x0, y0, x1, y1)
        name = NAMES[cp]
        glyphs[name] = pen.glyph()
        cmap[cp] = name
        order.append(name)

    if weight == THICK:
        for cp, base in HEAVY.items():
            src = LIGHT[[k for k, v in NAMES.items() if v == NAMES[cp].replace("heavy", "light")][0]]
            pen = TTGlyphPen(None)
            for _, x0, y0, x1, y1 in src:
                rect(pen, x0, y0, x1, y1)
            name = NAMES[cp]
            glyphs[name] = pen.glyph()
            cmap[cp] = name
            order.append(name)

    fb = FontBuilder(EM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    metrics = {n: (ADV, 0) for n in order}
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=880, descent=-120)
    fb.setupNameTable({
        "familyName": "Accelon Box",
        "styleName": "Regular",
        "uniqueFontIdentifier": "Accelon-Box-Regular",
        "fullName": "Accelon Box",
        "psName": "AccelonBox-Regular",
        "version": "Version 1.000",
        "copyright": "Generated by accelon (geometric box-drawing glyphs; no third-party outlines).",
    })
    fb.setupOS2(sTypoAscender=880, sTypoDescender=-120, usWinAscent=1000, usWinDescent=350)
    fb.setupPost()
    return fb


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "src", "accelon26", "fonts"))
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    os.makedirs(out, exist_ok=True)
    fb = build(THIN)
    ttf = os.path.join(out, "_accelon-box.ttf")
    fb.save(ttf)
    from fontTools.ttLib import TTFont
    f = TTFont(ttf)
    f.flavor = "woff2"
    woff = os.path.join(out, "accelon-box.woff2")
    f.save(woff)
    f.close()
    os.remove(ttf)
    print("%s  %d bytes  %d glyphs" % (woff, os.path.getsize(woff), len(fb.font.getGlyphOrder())))


if __name__ == "__main__":
    main()
